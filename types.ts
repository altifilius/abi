export enum ProjectStage {
  IDEA = 'IDEA',
  DRAFTING = 'DRAFTING',
  READY = 'READY',
  SUBMITTED = 'SUBMITTED',
}

export interface Project {
  id: string;
  title: string;
  description: string; // The "1-pager" generated by AI
  stage: ProjectStage;
  documents: ProjectDocument[];
  matchedFunds?: FundMatch[];
}

export interface ProjectDocument {
  id: string;
  name: string;
  type: 'required' | 'optional';
  status: 'missing' | 'uploaded' | 'verified';
  file?: File;
}

export interface Fund {
  id: string;
  code: string; // e.g., "1501", "1507"
  name: string;
  institution: 'TUBITAK' | 'KOSGEB' | 'EU';
  description: string;
  maxBudget: string;
  supportRate: string;
}

export interface FundMatch {
  fundId: string;
  score: number; // 0-100
  rationale: string;
  eligibilityStatus: 'eligible' | 'conditional' | 'ineligible';
}

export type IncorporationStepId = '1' | '2' | '3' | '4' | '5' | '6';

export interface IncorporationStep {
  id: IncorporationStepId;
  title: string;
  description: string;
  completed: boolean;
  dueDate?: string;
  category: 'legal' | 'tax' | 'compliance';
}

export interface ChatMessage {
  id: string;
  role: 'user' | 'model';
  text: string;
  timestamp: number;
}

// Persistence-specific types (localStorage-safe)
export type PersistedProjectDocument = Omit<ProjectDocument, 'file'>;

export interface ProjectPersistedState {
  version: number;
  description?: string;
  matchedFunds?: FundMatch[];
  documents?: PersistedProjectDocument[];
}
